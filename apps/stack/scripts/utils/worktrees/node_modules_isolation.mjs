import { rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { validateNodeModulesIsolation } from '@happier-dev/cli-common/nodeModulesIsolation';

export function getWorktreeDependencyIsolationNodeModulesDirs(repoRoot) {
  const root = resolve(String(repoRoot ?? ''));
  return [
    join(root, 'node_modules'),
    join(root, 'apps', 'ui', 'node_modules'),
    join(root, 'apps', 'cli', 'node_modules'),
    join(root, 'apps', 'server', 'node_modules'),
  ];
}

export async function validateWorktreeDependencyIsolation({ repoRoot, nodeModulesDirs } = {}) {
  const root = resolve(String(repoRoot ?? ''));
  return validateNodeModulesIsolation({
    repoRoot: root,
    nodeModulesDirs: nodeModulesDirs ?? getWorktreeDependencyIsolationNodeModulesDirs(root),
  });
}

export async function removePollutedNodeModulesDirs(result) {
  const dirs = Array.isArray(result?.pollutedNodeModulesDirs) ? result.pollutedNodeModulesDirs : [];
  for (const dir of dirs) {
    await rm(dir, { recursive: true, force: true });
  }
  return dirs;
}

export function formatDependencyIsolationFindings(result) {
  const findings = [...(result?.errors ?? []), ...(result?.warnings ?? [])];
  if (!findings.length) return '';
  return findings
    .map((finding) => {
      const target = finding.resolvedTargetPath ?? '<missing>';
      return `- ${finding.code}: ${finding.symlinkPath} -> ${target}`;
    })
    .join('\n');
}
