import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, rm, symlink, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { mkdtemp } from 'node:fs/promises';

import {
  getWorktreeDependencyIsolationNodeModulesDirs,
  removePollutedNodeModulesDirs,
  validateWorktreeDependencyIsolation,
} from './node_modules_isolation.mjs';

async function writeJson(path, value) {
  await writeFile(path, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

async function createHappierRepo(root) {
  await mkdir(root, { recursive: true });
  await writeJson(join(root, 'package.json'), {
    name: 'monorepo',
    private: true,
    workspaces: { packages: ['apps/*', 'packages/*'] },
  });
  await writeFile(join(root, 'yarn.lock'), '', 'utf8');
}

test('getWorktreeDependencyIsolationNodeModulesDirs covers root and app-local dependency trees', () => {
  const root = resolve('/repo');
  assert.deepEqual(getWorktreeDependencyIsolationNodeModulesDirs(root), [
    resolve('/repo/node_modules'),
    resolve('/repo/apps/ui/node_modules'),
    resolve('/repo/apps/cli/node_modules'),
    resolve('/repo/apps/server/node_modules'),
  ]);
});

test('validateWorktreeDependencyIsolation reports polluted app-local node_modules dirs', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'hstack-nm-isolation-'));
  t.after(async () => rm(dir, { recursive: true, force: true }));

  const current = join(dir, 'current');
  const other = join(dir, 'other');
  await createHappierRepo(current);
  await createHappierRepo(other);
  await mkdir(join(other, 'node_modules', 'zod'), { recursive: true });
  await writeJson(join(other, 'node_modules', 'zod', 'package.json'), { name: 'zod' });
  await mkdir(join(current, 'apps', 'ui', 'node_modules'), { recursive: true });
  await symlink(join(other, 'node_modules', 'zod'), join(current, 'apps', 'ui', 'node_modules', 'zod'), 'dir');

  const result = await validateWorktreeDependencyIsolation({ repoRoot: current });

  assert.equal(result.ok, false);
  assert.deepEqual(result.pollutedNodeModulesDirs, [resolve(current, 'apps', 'ui', 'node_modules')]);
});

test('removePollutedNodeModulesDirs deletes only validator-reported polluted dirs', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'hstack-nm-isolation-rm-'));
  t.after(async () => rm(dir, { recursive: true, force: true }));

  const polluted = join(dir, 'polluted', 'node_modules');
  const clean = join(dir, 'clean', 'node_modules');
  await mkdir(polluted, { recursive: true });
  await mkdir(clean, { recursive: true });

  await removePollutedNodeModulesDirs({ pollutedNodeModulesDirs: [polluted] });

  assert.equal(existsSync(polluted), false);
  assert.equal(existsSync(clean), true);
});
